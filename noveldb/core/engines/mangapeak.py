"""Article Image Queue's MangaPeak site contract, implemented for desktop and Pyodide."""

from datetime import datetime, timezone
from hashlib import md5
from html import escape
import json
import re
from urllib.parse import urlencode, urlsplit

from noveldb.core.engines.generic import clean_url, extract_metadata, soup_of, text_of


SITE = "\u0072\u006f\u006c\u0069\u0061\u0073\u0063\u0061\u006e.com"
_BOOK_PATH = re.compile(r"^/(?:manga|read)/([^/]+)(?:/|$)")
_READER_PATH = re.compile(r"^/read/([^/]+)/[^/]+-(\d+)/?$")


def knows(url: str) -> bool:
    parts = urlsplit(url)
    return (parts.scheme in ("http", "https") and (parts.hostname or "").removeprefix("www.") == SITE
            and bool(_BOOK_PATH.match(parts.path)))


def _chapter_query(manga_id: str, offset: int) -> str:
    # The public chapter-list request uses the time stamp generated by the site's reader.
    now = datetime.now(timezone.utc)
    stamp = int(now.timestamp())
    token = md5(f"{stamp}mng_ch_{now:%Y%m%d%H}".encode(), usedforsecurity=False).hexdigest()[:16]
    return urlencode({"manga_id": manga_id, "offset": offset, "limit": 500, "order": "ASC", "_t": token, "_ts": stamp})


class MangaPeakEngine:
    label = "Article Image Queue readers"
    knows = staticmethod(knows)

    def __init__(self, fetch, log=lambda _: None):
        self.fetch = fetch
        self.log = log

    def _json(self, origin, route, query, referer):
        response = self.fetch(f"{origin}{route}?{query}", referer=referer, headers={"Accept": "application/json"})
        if not response or response["status"] != 200:
            status = response["status"] if response else "no answer"
            raise RuntimeError(f"MangaPeak {route} returned {status}")
        payload = json.loads(response.get("text") or response.get("content") or "")
        if not isinstance(payload, dict) or payload.get("success") is not True:
            raise RuntimeError(f"MangaPeak {route} refused the request")
        return payload

    def parse_book(self, url):
        if not knows(url):
            return None
        parts = urlsplit(url)
        slug = _BOOK_PATH.match(parts.path)[1]
        origin = f"https://{parts.hostname}"
        book_url = f"{origin}/manga/{slug}/"
        response = self.fetch(book_url)
        if not response or response["status"] != 200:
            raise RuntimeError("MangaPeak series page could not be read")
        html = response.get("text") or ""
        soup = soup_of(html)
        node = soup.select_one("body[data-manga-id], .chapter-list[data-manga-id]")
        manga_id = str(node["data-manga-id"]) if node else ""
        if not manga_id.isdecimal():
            return None
        chapters, seen = [], set()
        offset = 0
        for _ in range(200):
            payload = self._json(origin, "/auth/manga-chapters", _chapter_query(manga_id, offset), book_url)
            rows = payload.get("chapters")
            if not isinstance(rows, list):
                raise RuntimeError("MangaPeak returned an invalid chapter list")
            added = 0
            for row in rows:
                if not isinstance(row, dict):
                    continue
                chapter_id = str(row.get("id") or "")
                link = clean_url(str(row.get("url") or ""), book_url)
                path = _READER_PATH.fullmatch(urlsplit(link).path) if knows(link) else None
                if not path or path[1] != slug or path[2] != chapter_id or chapter_id in seen:
                    continue
                seen.add(chapter_id)
                added += 1
                number = str(row.get("chapter") or len(chapters) + 1)
                title = str(row.get("title") or "").strip()
                name = f"Chapter {number}"
                if title and title.casefold() not in {"n/a", name.casefold()}:
                    name += f": {title}"
                locked = row.get("is_locked") is True or row.get("locked") is True
                chapters.append({"url": link, "name": name, "number": len(chapters) + 1,
                                 "bookUrl": book_url, "isPaid": locked or row.get("is_premium") is True,
                                 "isVIP": locked, "isAccessible": not locked})
            if not payload.get("has_more"):
                break
            if not rows or not added:
                raise RuntimeError("MangaPeak chapter pagination stopped making progress")
            offset += len(rows)
        else:
            raise RuntimeError("MangaPeak chapter pagination exceeded its limit")
        if not chapters:
            return None
        meta = extract_metadata(html, book_url, soup)
        return {"engine": "mangapeak", "ruleName": self.label, "bookUrl": book_url,
                "bookname": text_of(soup.find("h1")) or meta["title"], "author": meta["author"],
                "introduction": meta["description"], "coverUrl": meta["cover"], "tags": meta["tags"],
                "status": meta["status"], "chapters": chapters, "chapterCount": len(chapters)}

    def parse_chapter(self, chapter, book):
        url = chapter.get("url") or ""
        path = _READER_PATH.fullmatch(urlsplit(url).path) if knows(url) else None
        if not path:
            return None
        if chapter.get("isAccessible") is False:
            return {"_locked": True, "_lockReason": "this chapter requires access"}
        origin = f"https://{urlsplit(url).hostname}"
        book_url = f"{origin}/manga/{path[1]}/"
        payload = self._json(origin, "/auth/chapter-content", urlencode({"chapter_id": path[2]}), book_url)
        if payload.get("chapter_type") not in (None, "", "media") or not isinstance(payload.get("images"), list):
            raise RuntimeError("MangaPeak did not return an image chapter")
        pages = [clean_url(item, url) if isinstance(item, str) else "" for item in payload["images"]]
        if not pages or not all(pages):
            raise RuntimeError("MangaPeak returned an empty or invalid image list")
        return {"chapterName": chapter.get("name") or "", "contentText": "", "comic": True,
                "contentHtml": "".join(f'<p><img src="{escape(page)}" alt=""/></p>' for page in pages),
                "imageCount": len(pages), "imageReferer": book_url, "images": []}
